CatalogCameraEntry _cam({
  required String id,
  required String brand,
  required String model,
  required double w,
  required double h,
  String mount = 'PL',
  double dr = 14,
  int iso = 800,
  String log = 'LogC3',
  double? weight,
}) {
  return CatalogCameraEntry(
    externalId: id,
    brand: brand,
    model: model,
    sensorWidthMm: w,
    sensorHeightMm: h,
    mountType: mount,
    dynamicRangeStops: dr,
    nativeIso: iso,
    logFormats: log,
    weightKg: weight,
    sensorModes: [
      {
        'name': 'Open Gate',
        'widthMm': w,
        'heightMm': h,
        'cropFactor': 1.0,
      },
      {
        'name': '16:9',
        'widthMm': w,
        'heightMm': w / (16 / 9),
        'cropFactor': 1.0,
      },
      {
        'name': '2.39:1',
        'widthMm': w,
        'heightMm': w / 2.39,
        'cropFactor': 1.0,
      },
    ],
  );
}

CatalogLensEntry _prime({
  required String seriesId,
  required String brand,
  required String series,
  required double focal,
  required String coverage,
  double tStop = 2.0,
  String mount = 'PL',
  double imageCircle = 31.2,
  String lensType = 'spherical',
}) {
  return CatalogLensEntry(
    externalId: '${seriesId}_${focal.toInt()}',
    brand: brand,
    model: '$series ${focal.toInt()}mm',
    focalLength: focal,
    minTStop: tStop,
    formatCoverage: coverage,
    mountType: mount,
    imageCircleMm: imageCircle,
    lensType: lensType,
    closeFocusM: focal <= 25 ? 0.3 : 0.45,
  );
}

List<CatalogLensEntry> _primeSet({
