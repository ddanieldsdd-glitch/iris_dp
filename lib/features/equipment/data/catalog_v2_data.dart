CatalogCameraEntry applyRealSensorModes(CatalogCameraEntry cam) {
  final modes = kRealSensorModesByCameraId[cam.externalId];
  if (modes == null) return cam;
  return CatalogCameraEntry(
    externalId: cam.externalId,
    brand: cam.brand,
    model: cam.model,
    sensorWidthMm: cam.sensorWidthMm,
    sensorHeightMm: cam.sensorHeightMm,
    mountType: cam.mountType,
    sensorModes: modes,
    dynamicRangeStops: cam.dynamicRangeStops,
    colorScience: cam.colorScience,
    nativeIso: cam.nativeIso,
    logFormats: cam.logFormats,
    weightKg: cam.weightKg,
    powerDrawW: cam.powerDrawW,
    manufacturerUrl: cam.manufacturerUrl,
    series: cam.series,
    vintage: cam.vintage,
    rentalTags: cam.rentalTags,
    lukaCompatible: cam.lukaCompatible,
    lukaProfile: cam.lukaProfile,
  );
}

