import 'catalog_models.dart';

CatalogLensEntry _vintagePrime({
  required String seriesId,
  required String brand,
  required String series,
  required double focal,
  double tStop = 2.8,
  String coverage = 'S35',
  double imageCircle = 31.2,
  String mount = 'PL',
  List<String> rentalTags = const ['AbelCine', 'LensRentals'],
  bool isAnamorphic = false,
  double? squeezeRatio,
}) =>
    CatalogLensEntry(
      externalId: '${seriesId}_${focal.toInt()}',
      brand: brand,
      model: '$series ${focal.toInt()}mm',
      series: series,
      focalLength: focal,
      minTStop: tStop,
      formatCoverage: coverage,
      mountType: mount,
      imageCircleMm: imageCircle,
      lensType: isAnamorphic ? 'anamorphic' : 'vintage',
      vintage: true,
      rentalTags: rentalTags,
      isAnamorphic: isAnamorphic,
      squeezeRatio: squeezeRatio,
      closeFocusM: focal <= 35 ? 0.6 : 0.9,
      lukaProfile: {
        'manualSetup': true,
        'notes': 'Introducir focal ${focal.toInt()}mm y T$tStop manualmente en LUKA CineCamera',
      },
    );

List<CatalogLensEntry> _vintageSet({
  required String id,
  required String brand,
  required String series,
  required List<double> focals,
  double tStop = 2.8,
  String coverage = 'S35',
  double imageCircle = 31.2,
  List<String> rentalTags = const ['AbelCine', 'LensRentals'],
}) =>
    focals
        .map((f) => _vintagePrime(
              seriesId: id,
              brand: brand,
              series: series,
              focal: f,
              tStop: tStop,
              coverage: coverage,
              imageCircle: imageCircle,
              rentalTags: rentalTags,
            ))
        .toList();

